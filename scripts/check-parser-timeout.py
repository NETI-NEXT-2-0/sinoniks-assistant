#!/usr/bin/env python3
"""Exercise actual sandbox timeout and prove its container does not survive."""

import os
import subprocess
import tempfile
from pathlib import Path


def main():
    root = Path(__file__).resolve().parents[1]
    with tempfile.TemporaryDirectory(prefix="partner-parser-timeout-") as directory:
        source = Path(directory) / "source.docx"
        # Empty input is intentionally rejected; engine import/startup still exercises deadline.
        source.write_bytes(b"synthetic malformed source")
        env = os.environ.copy()
        env["PARTNER_PARSER_TIMEOUT_SECONDS"] = "1"
        before = subprocess.check_output(
            ["docker", "ps", "-aq", "--filter", "name=partner-parser-"], text=True
        ).splitlines()
        result = subprocess.run(
            [str(root / "scripts/run-parser.sh"), str(source), directory],
            env=env,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=25,
        )
        # Invalid DOCX exits too early; use a valid DOCX generated by the parser environment.
        if result.returncode != 124:
            subprocess.run(
                [
                    str(root / "parser/.venv/bin/python"),
                    "-c",
                    "from docx import Document; import sys; "
                    "d=Document(); d.add_paragraph('Synthetic timeout'); d.save(sys.argv[1])",
                    str(source),
                ],
                check=True,
            )
            result = subprocess.run(
                [str(root / "scripts/run-parser.sh"), str(source), directory],
                env=env,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                timeout=25,
            )
        assert result.returncode == 124, "Parser did not hit the configured deadline"
        after = subprocess.check_output(
            ["docker", "ps", "-aq", "--filter", "name=partner-parser-"], text=True
        ).splitlines()
        assert set(after) <= set(before), "Timed-out parser container survived cleanup"
        print("parser_deadline_and_container_cleanup_passed")


if __name__ == "__main__":
    main()
